internal val MASCOT_TIMELINE: List<MascotStep> =
    MASCOT_ROUTINE_WALK + MASCOT_ROUTINE_STICK + MASCOT_ROUTINE_JUMP

internal val MASCOT_CYCLE_MS: Long = MASCOT_TIMELINE.sumOf { it.durationMs.toLong() }

/** Waktu mulai gerakan aktif (melewati jeda pose 0 selama 900 ms) untuk tiap rangkaian (0 = jalan 3D, 1 = tongkat, 2 = lompat). */
internal fun mascotRoutineActiveOffsetMs(routineIndex: Int): Long {
    val r0 = MASCOT_ROUTINE_WALK.sumOf { it.durationMs.toLong() }
    val r1 = MASCOT_ROUTINE_STICK.sumOf { it.durationMs.toLong() }
    return when (routineIndex.mod(3)) {
        0 -> MASCOT_ROUTINE_WALK.first().durationMs.toLong()
        1 -> r0 + MASCOT_ROUTINE_STICK.first().durationMs.toLong()
        else -> r0 + r1 + MASCOT_ROUTINE_JUMP.first().durationMs.toLong()
    }
}

/** Indeks pose (0..40) pada waktu [elapsedMs] di dalam siklus animasi berkelanjutan. */
internal fun mascotPoseAt(elapsedMs: Long): Int {
    if (MASCOT_CYCLE_MS <= 0L) return 0
    var rem = elapsedMs.mod(MASCOT_CYCLE_MS)
    for (step in MASCOT_TIMELINE) {
        if (rem < step.durationMs) return step.pose
        rem -= step.durationMs
    }
    return 0
}

